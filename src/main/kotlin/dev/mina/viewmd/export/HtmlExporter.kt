package dev.mina.viewmd.export

import com.intellij.openapi.project.Project
import dev.mina.viewmd.css.CssResolver
import dev.mina.viewmd.css.CssStatus
import dev.mina.viewmd.settings.ViewMdSettings
import dev.mina.viewmd.util.HtmlUtils
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path

object HtmlExporter {

    fun generateStandaloneHtml(
        title: String,
        bodyHtml: String,
        project: Project?,
        isDark: Boolean = false,
        includeMermaid: Boolean? = null
    ): String {
        val builtInCss = loadResourceText("web/viewmd.css")
        val postprocessJs = loadResourceText("web/postprocess.js")

        // Include the heavy (~4.9MB) Mermaid bundle only when needed
        val needsMermaid = includeMermaid ?: (bodyHtml.contains("class=\"mermaid\"") ||
                bodyHtml.contains("class=\"language-mermaid\"") ||
                bodyHtml.contains("```mermaid"))

        val mermaidScriptTag = if (needsMermaid) {
            val mermaidJs = loadResourceText("web/vendor/mermaid.min.js")
            "<script>\n$mermaidJs\n</script>"
        } else {
            ""
        }

        val customCssText = resolveCustomCss(project)
        val safeCustomCss = customCssText.replace(Regex("</style>", RegexOption.IGNORE_CASE), "<\\/style>")
        val initialTheme = if (isDark) "dark" else "light"

        // Clean up any inner <body ...> tags generated by MarkdownUtil
        var sanitizedBody = bodyHtml
            .replace(Regex("<body[^>]*>", RegexOption.IGNORE_CASE), "")
            .replace(Regex("</body>", RegexOption.IGNORE_CASE), "")
            .trim()

        // Strip IDE-internal command runner elements (run buttons with relative commandRunner/*.png and href="#")
        sanitizedBody = sanitizedBody
            .replace(Regex("<a\\b[^>]*\\bdata-command=['\"][^'\"]*['\"][^>]*>.*?</a>", setOf(RegexOption.IGNORE_CASE, RegexOption.DOT_MATCHES_ALL)), "")
            .replace(Regex("<a\\b[^>]*class=['\"][^'\"]*run-icon[^'\"]*['\"][^>]*>.*?</a>", setOf(RegexOption.IGNORE_CASE, RegexOption.DOT_MATCHES_ALL)), "")

        // Strip IDE-internal duplicate code fence copy button
        sanitizedBody = sanitizedBody
            .replace(Regex("<div\\b[^>]*class=['\"][^'\"]*code-fence-highlighter-copy-button[^'\"]*['\"][^>]*>.*?</div>", setOf(RegexOption.IGNORE_CASE, RegexOption.DOT_MATCHES_ALL)), "")

        // Replace IDE-internal relative alert icons (alertIcons/*.png) with clean standalone emoji badges
        sanitizedBody = sanitizedBody
            .replace(Regex("<img\\b[^>]*class=['\"][^'\"]*markdown-alert-icon[^'\"]*['\"][^>]*src=['\"][^'\"]*alertIcons/([a-zA-Z]+)\\.png['\"][^>]*>", RegexOption.IGNORE_CASE)) { match ->
                val type = match.groupValues[1].lowercase()
                val emoji = when (type) {
                    "tip" -> "💡"
                    "important" -> "❗"
                    "warning" -> "⚠️"
                    "caution" -> "🛑"
                    else -> "ℹ️"
                }
                """<span class="viewmd-alert-icon" style="margin-right: 8px;">$emoji</span>"""
            }

        return """
        <!doctype html>
        <html lang="en" data-theme="$initialTheme">
        <head>
          <meta charset="utf-8">
          <meta name="viewport" content="width=device-width, initial-scale=1">
          <title>${HtmlUtils.escapeHtml(title)}</title>
          <style>
          $builtInCss
          $safeCustomCss
          </style>
          $mermaidScriptTag
        </head>
        <body>
          <button id="viewmd-theme-toggle" class="viewmd-theme-toggle" title="Toggle Light/Dark Theme" type="button">
            <span id="viewmd-theme-icon">${if (isDark) "☀️" else "🌙"}</span>
            <span id="viewmd-theme-text">${if (isDark) "Light Mode" else "Dark Mode"}</span>
          </button>
          <div class="viewmd-content">
            $sanitizedBody
          </div>
          <script>
          $postprocessJs
          </script>
        </body>
        </html>
        """.trimIndent()
    }

    fun exportToTempFile(
        title: String,
        bodyHtml: String,
        project: Project?,
        isDark: Boolean = false,
        includeMermaid: Boolean? = null
    ): Path {
        val html = generateStandaloneHtml(title, bodyHtml, project, isDark, includeMermaid)
        val tempFile = Files.createTempFile("viewmd-export-", ".html")
        Files.writeString(tempFile, html, StandardCharsets.UTF_8)
        return tempFile
    }

    private fun resolveCustomCss(project: Project?): String {
        val path = try {
            ViewMdSettings.instance.state.customCssPath
        } catch (e: Throwable) {
            ""
        }
        val status = CssResolver.resolve(path, project)
        if (status is CssStatus.Valid) {
            return try {
                Files.readString(status.path, StandardCharsets.UTF_8)
            } catch (e: Exception) {
                ""
            }
        }
        return ""
    }

    private fun loadResourceText(resourcePath: String): String {
        val normalized = if (resourcePath.startsWith("/")) resourcePath else "/$resourcePath"
        val stream = HtmlExporter::class.java.getResourceAsStream(normalized)
            ?: HtmlExporter::class.java.classLoader.getResourceAsStream(resourcePath)
        return stream?.use {
            String(it.readAllBytes(), StandardCharsets.UTF_8)
        } ?: ""
    }
}
